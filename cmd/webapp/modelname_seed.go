// 模型名归一化的证据源：启动种子化 + 成功累加（v0.31.2）。
//
// 独立成文件是因为它是"启动装配 + 热路径记账"两件事，与归一化算法本身无关。
package main

import "log"

// seedRecentModels 启动时把**成功服务过**的模型名装进内存清单。
//
// 为什么必须做（本机实测）：进程刚启动时 /v1/models 缓存是空的，池内成本台账
// 也未必有值（只覆盖最近 6h 且未必落盘）—— 那时"大小写归一 / 分隔符归一"会静默失效：
// 实测重启后 `GLM-5.3` 仍 404，而同一次部署里 `" glm-5.3 "` 已经 200。
// usage_logs 是持久的，用它给归一化一个**跨重启可靠且零出站**的证据源。
//
// 只取 status='ok' 的行：失败的那次写法可能是错的，把错的写进清单会让
// 下一次把**正确**写法归一成错的（最危险的方向）。
func seedRecentModels(s *Store) {
	ids, err := s.RecentOKModels(200)
	if err != nil {
		// 种子化失败不影响正确性（归一化退化为"去空白 + 剥前缀"），但要说出来 ——
		// 否则"为什么大小写写法没被纠正"会变成又一个需要翻代码才能回答的问题。
		log.Printf("WARN: [proxy] 模型名清单种子化失败（归一化将只用缓存与兜底清单）：%v", err)
		return
	}
	for _, m := range ids {
		rememberModel(m)
	}
	if len(ids) > 0 {
		log.Printf("INFO: [proxy] 已从历史用量载入 %d 个模型名（用于模型名写法归一）", len(ids))
	}
}
