// tier.go 「这类错误能否作为摘除账号的依据」的**单一判定点**（v0.24.7）。
//
// ## 为什么要有这个文件
//
// 2026-10-13 的事故（一个风控窗口内批量误杀 30 个健康账号）成因**不是**某个分支写错了，
// 而是**同一个错误码在不同链路上有两套纪律**：健康检测侧早已写明「一次 12153 可能是网络抖动
// / refresh 竞态，一次就杀号会误杀」并走累计阈值，而生产转发链路与旧网关上仍是「一次即
// Disable」。哪条链路先被改，就只有那条链路变对 —— 这种漂移会持续制造同类事故。
//
// 同类开源项目的共识做法（见 docs/多上游网关可靠性调研-20261013.md）是把错误**显式分层**：
// `gpt-load` 分「可忽略 / **不计数** / 可重试」，并明确写出「配额耗尽不是 key 健康问题，
// 不该加失败计数」。本文件按同一思路回答一个更窄、但更关键的问题：
//
//	**这类错误，够不够作为"把这个账号从池子里摘掉"的依据？**
//
// 注意它回答的是"**可否**"而不是"**必须**"：即使返回 true，具体强度仍由处置分支决定
// （累计阈值 / 即时）。返回 false 则**任何**停用或删除都必须先退化为可逆处置。
//
// ## 判定口径
//
// 只认**指向账号自身状态**且有终态语义的两类：
//
//	ErrSessionDead  —— 会话失效（12153）：token 真的没了，需重登（但可能是抖动/竞态，
//	                   故"可用作依据"≠"一次即摘"，仍走累计阈值）。
//	ErrAccountFault —— 账号级授权/配额故障：11140（含 displayMsg 的账号级限制）、
//	                   14017（试用未开通）。是上游对**账号**的判定。
//
// 其余一律 false，理由逐条写在各分支上 —— 这一段的用意是：**将来新增 ErrKind 时，
// 必须来这里回答一次"它指不指向账号"**，而不是在某个 switch 里顺手写一个 Disable。

package upstream

// MayRetireAccount 报告该错误类型**是否可以**作为「摘除账号（停用 / 删除）」的依据。
//
// 调用方约定：返回 false 时，处置必须落在**可逆**空间内（软冷却 / 计数 / 只报告）。
// 见 cmd/webapp 的 retireAccount —— 那是本判定的唯一执行闸门。
//
// v0.24.8 补充回答（新增 ErrChannelDenied 时的必答项）：
//
//	ErrChannelDenied（11128 渠道/客户端指纹拒绝）→ **false**。
//	它指向「这次请求/这个客户端指纹被上游渠道策略拒绝」，与账号自身状态无关；
//	换账号（本仓每号独立的 X-Machine-ID / X-Session-ID）本身就可能通过，
//	因此正确处置是「零罚 + 轮转」，绝不是摘号。
//
//	特别提醒：它与 ErrAccountFault 共用同一句 msg（"request illegal"），
//	两者的区分**只能靠 business code**（11128 vs 11140）。Classify 已把 11128
//	前置判定，防止它落进 ErrAccountFault 而获得摘除资格。
func MayRetireAccount(kind ErrKind) bool {
	switch kind {
	case ErrSessionDead, ErrAccountFault:
		return true
	default:
		return false
	}
}

// RetireEligibleHint 供日志 / 运维界面解释"为什么这个号被摘了"的统一措辞。
func RetireEligibleHint() string {
	return "仅「会话失效（12153）」与「账号级授权/配额故障（11140 / 14017）」可作为摘除账号的依据；" +
		"限流、WAF、5xx、传输层、余额耗尽、请求级错误一律只做可逆处置"
}
